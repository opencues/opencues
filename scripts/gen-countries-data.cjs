#!/usr/bin/env node
// Regenerates packages/opencues-runtime/src/blanks/countries-data.json from
// two stable static sources, joined on country name:
//   - mledoze/countries  → capital, region, area, currency, languages, aliases
//   - samayo/country-json → population (mledoze omits it)
//
// Why bundled (not a live API): restcountries.com (the blank's original
// source) was fully deprecated June 2026 — every path 301s to a
// deprecation notice. A bundled static dataset can't die. Country facts
// are stable enough that a periodic regen (re-run this script) is fine.
//
// Usage: node scripts/gen-countries-data.cjs
const fs = require('fs');
const path = require('path');
const https = require('https');

const MLEDOZE = 'https://raw.githubusercontent.com/mledoze/countries/master/countries.json';
const POP = 'https://raw.githubusercontent.com/samayo/country-json/master/src/country-by-population.json';
// Emit a .ts module (not .json) so it compiles into dist via tsc (no
// copy step needed for the CC/OC forks) AND bundles cleanly under esbuild
// (chrome). Importing JSON would need resolveJsonModule + a per-build copy.
const OUT = path.join(__dirname, '..', 'packages', 'opencues-runtime', 'src', 'blanks', 'countries-data.ts');

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return fetchJson(res.headers.location).then(resolve, reject);
      }
      if (res.statusCode !== 200) return reject(new Error(`${url} → HTTP ${res.statusCode}`));
      let s = '';
      res.on('data', c => (s += c));
      res.on('end', () => { try { resolve(JSON.parse(s)); } catch (e) { reject(e); } });
    }).on('error', reject);
  });
}

function norm(s) {
  return String(s || '').toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/\s+/g, ' ').trim();
}

(async () => {
  const [countries, pops] = await Promise.all([fetchJson(MLEDOZE), fetchJson(POP)]);

  // population lookup by normalised common name.
  const popByName = new Map();
  for (const p of pops) popByName.set(norm(p.country), p.population);
  // A few name reconciliations between the two sources.
  const POP_ALIASES = {
    'united states': 'united states of america',
    'czechia': 'czech republic',
    'dr congo': 'democratic republic of the congo',
    'republic of the congo': 'congo',
    'south korea': 'korea south',
    'north korea': 'korea north',
    'myanmar': 'myanmar burma',
  };

  const out = {};
  let withPop = 0;
  for (const c of countries) {
    const common = c.name && c.name.common;
    if (!common) continue;
    const key = norm(common);

    // population: try direct, then alias, then a couple of fuzzy fallbacks.
    let population = popByName.get(key);
    if (population == null && POP_ALIASES[key]) population = popByName.get(norm(POP_ALIASES[key]));
    if (population == null) {
      for (const alt of (c.altSpellings || [])) {
        const a = popByName.get(norm(alt));
        if (a != null) { population = a; break; }
      }
    }
    if (population != null) withPop++;

    const currencyCode = c.currencies ? Object.keys(c.currencies)[0] : null;
    const currencyName = currencyCode && c.currencies[currencyCode] ? c.currencies[currencyCode].name : null;

    const entry = {
      name: common,
      capital: (c.capital && c.capital[0]) || null,
      population: population != null ? population : null,
      region: c.region || null,
      area: typeof c.area === 'number' ? c.area : null,
      currency: currencyCode ? { code: currencyCode, name: currencyName } : null,
      languages: c.languages ? Object.values(c.languages).slice(0, 3) : [],
    };

    // Index by common name + cca2/cca3/cioc + altSpellings so lookups like
    // "usa" / "uk" / "south korea" resolve.
    const keys = new Set([key]);
    for (const k of [c.cca2, c.cca3, c.cioc, ...(c.altSpellings || [])]) {
      const nk = norm(k);
      if (nk) keys.add(nk);
    }
    for (const k of keys) if (!out[k]) out[k] = entry;
  }

  const header = `// AUTO-GENERATED by scripts/gen-countries-data.cjs — do not edit by hand.\n`
    + `// Sources: mledoze/countries (capital/region/area/currency/languages) +\n`
    + `// samayo/country-json (population), joined on country name. Bundled (not a\n`
    + `// live API) because restcountries.com — the blank's original source — was\n`
    + `// fully deprecated June 2026. Re-run the generator to refresh.\n\n`;
  const types = `export interface CountryFacts {\n`
    + `  readonly name: string;\n`
    + `  readonly capital: string | null;\n`
    + `  readonly population: number | null;\n`
    + `  readonly region: string | null;\n`
    + `  readonly area: number | null;\n`
    + `  readonly currency: { readonly code: string; readonly name: string | null } | null;\n`
    + `  readonly languages: readonly string[];\n`
    + `}\n\n`;
  const body = `const COUNTRIES: Record<string, CountryFacts> = ${JSON.stringify(out)};\n\nexport default COUNTRIES;\n`;
  fs.writeFileSync(OUT, header + types + body);
  const bytes = fs.statSync(OUT).size;
  console.log(`countries-data.ts: ${countries.length} countries, ${withPop} with population, ${Object.keys(out).length} lookup keys, ${(bytes / 1024).toFixed(0)}KB → ${OUT}`);
})().catch(e => { console.error('FATAL:', e.message); process.exit(1); });
