/**
 * Production benchmark — drives the REAL `BlankIntentClassifier` from
 * `@opencues/core` (its `classifyRaw`), so it measures EXACTLY the prompt
 * users run. There is no bench-local prompt: the classifier's SYSTEM
 * prompt + catalog generation live solely in
 * `packages/opencues-core/src/sources/blank-intent-source.ts`. Editing
 * that file is automatically what this bench measures. (The sibling
 * `run.ts` is the original PoC with a bench-local prompt copy — kept for
 * history; THIS file is the live bench, mirroring the transform-blank
 * `prod.ts` lesson about prompt drift.)
 *
 * Usage:
 *   CEREBRAS_API_KEY=xxx npx tsx tests/benchmarks/blank-intent/prod.ts [--provider cerebras|groq|gemini] [--parallel N]
 *
 * Scored exactly (no LLM judge): recall (invoke + blank + action + value),
 * precision (prose cedes), safety (keyword-free cedes — note these would
 * never reach Phase 2 in production because the keyword pre-gate blocks
 * them; included to measure the classifier's standalone over-reach).
 */

