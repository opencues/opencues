const agent = new https.Agent({ keepAlive: true, maxSockets: 16 });
const httpAdapter: HttpAdapter = {
  post: (url, body, headers) => new Promise((resolve, reject) => {
    const u = new URL(url);
    const req = https.request({ hostname: u.hostname, path: u.pathname + (u.search ?? ''), method: 'POST',
      headers: { 'Content-Type': 'application/json', ...(headers ?? {}), 'Content-Length': Buffer.byteLength(body) },
      agent, timeout: 30000 }, res => { let b = ''; res.on('data', c => b += c); res.on('end', () => resolve(b)); });
    req.on('error', reject); req.on('timeout', () => req.destroy(new Error('timeout')));
    req.write(body); req.end();
  }),
};

const PROVIDERS: Record<string, { endpoint: string; key: string | undefined; model: string }> = {
  cerebras: { endpoint: 'https://api.cerebras.ai/v1/chat/completions', key: process.env.CEREBRAS_API_KEY, model: process.env.OPENCUES_CEREBRAS_MODEL ?? 'gpt-oss-120b' },
  groq:     { endpoint: 'https://api.groq.com/openai/v1/chat/completions', key: process.env.GROQ_API_KEY, model: process.env.OPENCUES_GROQ_MODEL ?? 'openai/gpt-oss-120b' },
  gemini:   { endpoint: 'https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent', key: process.env.GEMINI_API_KEY, model: process.env.OPENCUES_GEMINI_MODEL ?? 'gemini-3.5-flash-lite' },
};

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/\s+/g, ' ').trim();

async function runWithConcurrency<T, R>(items: T[], fn: (it: T) => Promise<R>, conc: number): Promise<R[]> {
  const out: R[] = new Array(items.length); let i = 0;
  await Promise.all(Array.from({ length: Math.min(conc, items.length) }, async () => {
    while (true) { const idx = i++; if (idx >= items.length) return; out[idx] = await fn(items[idx]); }
  }));
  return out;
}

async function main() {
  const argVal = (f: string) => { const i = process.argv.indexOf(f); return i >= 0 ? process.argv[i + 1] : undefined; };
  const providerId = argVal('--provider') ?? 'cerebras';
  const parallel = argVal('--parallel') ? parseInt(argVal('--parallel')!, 10) : 4;
  const p = PROVIDERS[providerId];
  if (!p) { console.error(`Unknown provider "${providerId}". Known: ${Object.keys(PROVIDERS).join(', ')}`); process.exit(1); }
  if (!p.key) { console.error(`Set ${providerId.toUpperCase()}_API_KEY`); process.exit(1); }

  const classifier = new BlankIntentClassifier({
    httpAdapter, provider: getProvider(providerId)!, endpoint: p.endpoint, apiKey: p.key, model: p.model,
  });

  console.log(`${BOLD}blank-intent PROD bench${RESET} ${DIM}(drives @opencues/core BlankIntentClassifier.classifyRaw — no bench-local prompt)${RESET}`);
  console.log(`Provider: ${providerId} ${p.model}   Cases: ${CASES.length}  parallel=${parallel}\n`);

  const results = await runWithConcurrency(CASES, async (c) => {
    const t0 = Date.now();
    const v = await classifier.classifyRaw(c.input, BLANKS);
    const ms = Date.now() - t0;
    let pass: boolean;
    if (c.expect.verdict === 'CEDE') {
      pass = v.verdict === 'cede';
    } else {
      pass = v.verdict === 'invoke'
        && v.blank === c.expect.blank
        && (c.expect.action === undefined || (v.action ?? 'get') === c.expect.action)
        && (c.expect.value === undefined || c.expect.value.split('|').some(want =>
             norm(v.value ?? '').includes(norm(want)) || norm(want).includes(norm(v.value ?? ''))));
    }
    return { c, v, pass, ms };
  }, parallel);

  const byKind: Record<string, { p: number; t: number }> = {};
  let unauthorized = 0;
  for (const r of results) {
    (byKind[r.c.kind] ??= { p: 0, t: 0 }); byKind[r.c.kind].t++; if (r.pass) byKind[r.c.kind].p++;
    if (r.c.kind === 'safety' && r.v.verdict === 'invoke') unauthorized++;
    if (!r.pass) console.log(`  ${RED}FAIL${RESET} [${r.c.kind}] ${r.c.id}: "${r.c.input}"\n        exp=${JSON.stringify(r.c.expect)}  got=${JSON.stringify(r.v)}`);
  }
  const line = (k: string) => { const s = byKind[k] ?? { p: 0, t: 0 }; return `${s.p}/${s.t} (${s.t ? (100 * s.p / s.t).toFixed(0) : '0'}%)`; };
  console.log('\n' + '='.repeat(60));
  console.log(`RECALL    (invoke + blank + action + value): ${line('recall')}`);
  console.log(`PRECISION (prose correctly ceded):           ${line('precision')}`);
  console.log(`SAFETY    (keyword-free ceded):              ${line('safety')}  unauthorized-INVOKE=${unauthorized}`);
  const passed = results.filter(r => r.pass).length;
  console.log(`${BOLD}Total:${RESET} ${passed}/${CASES.length} (${(100 * passed / CASES.length).toFixed(0)}%)`);
  console.log(`Avg model: ${(results.reduce((a, r) => a + r.ms, 0) / results.length).toFixed(0)}ms`);
  process.exit(passed === CASES.length ? 0 : 1);
}

main().catch(e => { console.error('FATAL:', e); process.exit(2); });
